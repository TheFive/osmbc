#!/usr/bin/env node
// Splits one OSMBC config file into a technical and an editorial file
// (rules in util/configSplit.js). The technical file gets
// `editorial_config` pointing to the editorial file, so OSMBC loads both.
//
//   node tools/split-config.mjs <config file> <technical out> <editorial out>
//
// Existing output files are not overwritten. YAML comments are not kept.

import fs from "fs";
import path from "path";
import { isDeepStrictEqual } from "util";
import { load as yamlLoad, dump as yamlDump } from "js-yaml";
import { splitConfig, mergeConfigs } from "../util/configSplit.js";

function fail(message) {
  console.error(message);
  process.exit(1);
}

const [input, technicalOut, editorialOut] = process.argv.slice(2);
if (!input || !technicalOut || !editorialOut) {
  fail("Usage: node tools/split-config.mjs <config file> <technical out> <editorial out>");
}
for (const out of [technicalOut, editorialOut]) {
  if (fs.existsSync(out)) fail("Output file exists, not overwritten: " + out);
}

const text = fs.readFileSync(input, "utf8");
const full = input.endsWith(".json") ? JSON.parse(text) : yamlLoad(text);
if (full.editorial_config) fail(input + " already has editorial_config, it is split already.");

const { technical, editorial, unknown } = splitConfig(full);

// the editorial file is found relative to the directory of the technical file
const technicalDir = path.dirname(path.resolve(technicalOut));
const editorialPath = path.resolve(editorialOut);
technical.editorial_config = path.dirname(editorialPath) === technicalDir
  ? path.basename(editorialPath)
  : editorialPath;

// check: merging both again gives the original config
const check = mergeConfigs(technical, editorial);
delete check.config.editorial_config;
if (check.conflicts.length > 0 || !isDeepStrictEqual(check.config, full)) {
  fail("Internal error: the split files don't merge back into the original, nothing written.");
}

const header = "# Generated by tools/split-config.mjs from " + path.basename(input) + "\n";
const options = { lineWidth: -1, noRefs: true };
fs.writeFileSync(technicalOut, header + "# Technical part: server, database, secrets.\n" + yamlDump(technical, options), { mode: 0o600 });
fs.writeFileSync(editorialOut, header + "# Editorial part: languages, export, workflow.\n" + yamlDump(editorial, options));

console.info("Technical: " + technicalOut + " (" + Object.keys(technical).length + " keys)");
console.info("Editorial: " + editorialOut + " (" + Object.keys(editorial).length + " keys)");
if (unknown.length > 0) {
  console.info("Unknown keys, put into the technical file - check them: " + unknown.join(", "));
}
